CREATE TABLE IF NOT EXISTS questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  answer TEXT NOT NULL DEFAULT '',
  is_public BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL,
  answered_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_questions_public
  ON questions (is_public, answered_at DESC);

CREATE TABLE IF NOT EXISTS question_submission_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_submission_events_rate
  ON question_submission_events (ip_hash, created_at);

CREATE TABLE IF NOT EXISTS memories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  words JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  approved_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_memories_public
  ON memories (approved, approved_at DESC);

CREATE TABLE IF NOT EXISTS interview_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT UNIQUE,
  answers JSONB NOT NULL,
  consent_to_keywords BOOLEAN NOT NULL DEFAULT FALSE,
  keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_public BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL,
  reviewed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_interviews_public
  ON interview_submissions (is_public, reviewed_at DESC);
